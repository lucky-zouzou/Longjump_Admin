import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),target=new URL('lib/backup-version.mjs',root);
const migrations=readdirSync(new URL('drizzle/',root)).filter(n=>n.endsWith('.sql')).sort().map(name=>({name,sha256:createHash('sha256').update(readFileSync(new URL('drizzle/'+name,root))).digest('hex')}));
const output='// Generated by scripts/backup-manifest.mjs. Do not edit by hand.\nexport const releaseMigrations='+JSON.stringify(migrations,null,2)+';\n';
if(process.argv.includes('--check')){
  const {releaseMigrations}=await import(target.href);
  if(JSON.stringify(releaseMigrations)!==JSON.stringify(migrations))throw Error('Backup migration manifest is stale; run node scripts/backup-manifest.mjs');
}else writeFileSync(target,output);
