export function smallTalk(question) {
  const q=question.trim().toLowerCase().replace(/[\s，。！？，,.!?～~]+/gu,'').replace(/[呀啊啦哟哦哈]+$/u,'');
  if(/^(早|早安|早上好|早上好小品)$/.test(q))return '早呀！今天想先忙哪件事？';
  if(/^(你好|您好|嗨|哈喽|hello|hi|在吗|在不在|小品在吗)$/.test(q))return '在呢！是来找个入口，还是有哪一步卡住了？';
  if(/^(谢|多谢|谢谢|谢了|谢谢你|谢谢小品|谢谢小品同学|辛苦了|辛苦你了)$/.test(q))return '不客气，下次还喊我！';
  if(/^(收到|明白了|懂了|了解了|知道了|搞定了|搞懂了)$/.test(q))return '好嘞！要接着看，喊我就行。';
  if(/^(卡住了|我卡住了|没看懂|我没看懂)$/.test(q))return '卡在哪儿啦？告诉我你在哪个页面、点了哪个按钮，咱们从那一步看。';
  if(/^(再见|拜拜|下次见)$/.test(q))return '回见，下次聊！';
  return '';
}

