export function encouragementFor(reply, recentLines=[], variation=0) {
  let kind='guide';
  if(reply.intent==='unknown')kind='stuck';
  else if(reply.intent==='public')kind='data';
  else if(['step','handoff','chat','choose','live'].includes(reply.intent))kind=reply.intent;
  const options=closings[kind];
  // recentLines is newest first. Prefer unused lines, then the least recently shown.
  const unused=options.filter(line=>!recentLines.includes(line));
  if(unused.length)return unused[Math.floor(variation*unused.length)];
  return options.reduce((oldest,line)=>recentLines.indexOf(line)>recentLines.indexOf(oldest)?line:oldest);
}
