export function guidesFor(actor) {
  const pages = navigationForRole(actor.role);
  const start = builtinGuides.find(g=>g.id===starts[actor.role]);
  const additional = (actor.handbook?.guides||[]).map(g=>({
    ...g, page:g.page==='@work'?(start?.page||pages[0]):g.page, privateHandbook:true
  }));
  return [...builtinGuides,...additional].filter(g => pages.includes(g.page) && (!g.roles || g.roles.includes(actor.role)) &&
    (!g.permission || hasPermission(actor.role,g.permission)) &&
    (g.page !== 'business-actions' || canReadActions(actor)) &&
    !(['wholesale','distribution'].includes(g.page) && actor.role === '运营' && actor.site !== '印尼'));
}

const starts = {'管理员':'action-review','运营':'sales-import','财务':'finance-day','供应链':'plan-submit','运营主管':'action-review','工厂':'factory-delivery','海运':'shipping','销售':'wholesale','达人BD':'bd-follow','拍摄剪辑':'studio','新品开发':'new-product'};
export function firstGuide(actor, allowed) {
  return allowed.find(g => g.id === starts[actor.role]) || allowed[0];
}
export function publicGuide({id,title,page,steps,next}) { return {id,title,page,steps,next}; }

export function findGuide(question, allowed) {
  const q = question.toLowerCase();
  const spoken=q.trim().replace(/[？?。！!]+$/u,'');
  const suggested=allowed.find(g=>guideQuestion(g.title).toLowerCase().replace(/[？?。！!]+$/u,'')===spoken);
  if(suggested)return suggested;
  return allowed.filter(g => !g.dailyRole || q === g.title.toLowerCase()).map(g => ({g,score:g.keywords.reduce((n,w)=>n+(q.includes(w.toLowerCase())?w.length:0),0)+(q.includes(g.title.toLowerCase())?20:0)}))
    .filter(x=>x.score>0).sort((a,b)=>b.score-a.score)[0]?.g;
}
